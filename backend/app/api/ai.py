def generate_title_from_content(content: str) -> str:
    cleaned = content.strip().split("\n")[0]
    words = cleaned.split()
    if len(words) > 7:
        title = " ".join(words[:7]) + "..."
    else:
        title = " ".join(words)
    return title[:60] if title else "New Chat"

def build_conversation_context(
    db: Session,
    conversation_id: int,
    current_msg_id: int,
    current_content: str,
    max_turns: int = 25,
    char_budget: int = 20000,
    max_single_msg_len: int = 3000
) -> list:
    """
    Builds a token-budgeted, sliding-window conversation history:
    - Retains up to max_turns recent messages.
    - Limits total past characters to char_budget (~5,000 tokens) to prevent context overflow.
    - Truncates oversized single past messages to prevent one huge paste from wiping out context.
    - Appends the current user turn cleanly.
    """
    raw_past = (
        db.query(Message)
        .filter(Message.conversation_id == conversation_id, Message.id < current_msg_id)
        .order_by(Message.id.desc())
        .limit(max_turns + 5)
        .all()
    )

    budget_consumed = 0
    selected_messages = []

    for msg in raw_past:
        content = (msg.content or "").strip()
        if not content:
            continue
        if len(content) > max_single_msg_len:
            half = max_single_msg_len // 2
            content = content[:half] + "\n...[truncated for context efficiency]...\n" + content[-half:]

        msg_len = len(content)
        if budget_consumed + msg_len > char_budget:
            break

        selected_messages.append({"role": msg.role, "content": content})
        budget_consumed += msg_len
        if len(selected_messages) >= max_turns:
            break

    selected_messages.reverse()
    selected_messages.append({"role": "user", "content": current_content})
    return selected_messages

def _persist_assistant_message(
    conversation_id: int,
    full_response_text: str,
    sources_found: list,
    query_text: str
) -> tuple:
    new_db = SessionLocal()
    assistant_msg_id = None
    current_title = "Chat"
    try:
        saved_content = full_response_text.strip() or "⚠️ No response was generated by the AI service."
        assistant_msg = Message(
            conversation_id=conversation_id,
            role="assistant",
            content=saved_content
        )
        new_db.add(assistant_msg)
        new_db.commit()
        new_db.refresh(assistant_msg)
        assistant_msg_id = assistant_msg.id

        for src in sources_found:
            db_src = Source(
                message_id=assistant_msg.id,
                title=src.get("title", ""),
                url=src.get("url", ""),
                source_name=src.get("source_name", "Web Source"),
                snippet=src.get("snippet", "")
            )
            new_db.add(db_src)
        new_db.commit()

        conv_obj = new_db.query(Conversation).filter(Conversation.id == conversation_id).first()
        if conv_obj:
            conv_obj.updated_at = datetime.utcnow()
            if conv_obj.title == "New Chat":
                conv_obj.title = generate_title_from_content(query_text)
            new_db.commit()
            current_title = conv_obj.title
    except Exception as db_err:
        print(f"[AI Stream] DB error saving assistant message: {db_err}")
    finally:
        new_db.close()
    return assistant_msg_id, current_title

@router.post("/chat/stream")
async def chat_stream(
    req: SendMessageRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    if not req.content.strip() and not req.file_extracted_text:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message content or document is required."
        )

    # 1. Get or create conversation
    if req.conversation_id:
        conversation = (
            db.query(Conversation)
            .filter(Conversation.id == req.conversation_id, Conversation.user_id == current_user.id)
            .first()
        )
        if not conversation:
            raise HTTPException(status_code=404, detail="Conversation not found.")
    else:
        # Create a new conversation
        title = generate_title_from_content(req.content)
        conversation = Conversation(
            user_id=current_user.id,
            title=title
        )
        db.add(conversation)
        db.commit()
        db.refresh(conversation)

    # 2. Save user message
    user_msg = Message(
        conversation_id=conversation.id,
        role="user",
        content=req.content.strip(),
        file_name=req.file_name,
        file_url=req.file_url,
        file_type=req.file_type
    )
    db.add(user_msg)
    conversation.updated_at = datetime.utcnow()
    db.commit()
    db.refresh(user_msg)

    # 3. Fetch user settings & resolve user preferred identity
    user_settings = db.query(UserSettings).filter(UserSettings.user_id == current_user.id).first()
    custom_system_prompt = user_settings.system_prompt if user_settings else None
    preferred_model = req.model or (user_settings.default_model if user_settings else None)

    # Resolve natural preferred name from authenticated profile or memory
    preferred_name = current_user.preferred_name
    if not preferred_name and custom_system_prompt:
        mem_match = re.search(r"(?:my name is|call me|i am|name:)\s+([A-Za-z]+)", custom_system_prompt, re.IGNORECASE)
        if mem_match:
            preferred_name = extract_preferred_name(mem_match.group(1))

    # Detect returning user status across conversations or turns
    past_convs_count = db.query(Conversation).filter(
        Conversation.user_id == current_user.id,
        Conversation.id != conversation.id
    ).count()
    prior_msgs_count = db.query(Message).filter(
        Message.conversation_id == conversation.id,
        Message.id < user_msg.id
    ).count()
    is_returning_user = (past_convs_count > 0 or prior_msgs_count > 0)

    # 4. Fetch token-budgeted sliding window conversation context (up to 25 turns)
    conv_history = build_conversation_context(
        db=db,
        conversation_id=conversation.id,
        current_msg_id=user_msg.id,
        current_content=req.content,
        max_turns=25,
        char_budget=20000
    )

    conversation_id = conversation.id
    user_id = current_user.id
    file_extracted = req.file_extracted_text
    file_name = req.file_name
    query_text = req.content
    web_search_flag = req.enable_web_search
    image_gen_flag = req.enable_image_generation

    async def sse_event_stream() -> AsyncGenerator[str, None]:
        # Yield initial conversation info event immediately
        init_data = json.dumps({
            "type": "init",
            "conversation_id": conversation_id,
            "title": conversation.title,
            "user_message_id": user_msg.id
        })
        yield f"data: {init_data}\n\n"

        # Immediately notify client that LOKR AI is thinking
        thinking_init = json.dumps({
            "type": "status",
            "message": "LOKR AI is thinking..."
        })
        yield f"data: {thinking_init}\n\n"

        # Send all messages (including greetings) directly to the configured AI model

        # Check if user requested an image
        need_image = should_generate_image(query_text, image_gen_flag)
        if need_image:
            img_status = json.dumps({
                "type": "status",
                "message": "🎨 Creating your image with AI..."
            })
            yield f"data: {img_status}\n\n"

            clean_prompt = clean_image_prompt(query_text)
            img_result = await generate_ai_image(clean_prompt)

            # Inform frontend about the generated image
            img_event = json.dumps({
                "type": "image",
                "image_url": img_result["image_url"],
                "prompt": img_result["prompt"]
            })
            yield f"data: {img_event}\n\n"

            if img_result.get("is_factual"):
                full_response_text = f"Here is the accurate high-definition map/image for **\"{img_result['prompt']}\"**:\n\n![{img_result['prompt']}]({img_result['image_url']})\n\n*Official high-resolution map with states and borders. You can download or view full-screen.*"
            else:
                full_response_text = f"Here is the image created for **\"{img_result['prompt']}\"**:\n\n![{img_result['prompt']}]({img_result['image_url']})\n\n*Rendered in 768×768 high definition. You can download or view full-screen.*"

            for token in full_response_text.split(" "):
                token_data = json.dumps({"type": "token", "content": token + " "})
                yield f"data: {token_data}\n\n"

            # Save assistant message in threadpool
            def _save_image_msg():
                new_db = SessionLocal()
                msg_id = None
                t = conversation.title
                try:
                    assistant_msg = Message(
                        conversation_id=conversation_id,
                        role="assistant",
                        content=full_response_text,
                        file_name=f"Generated Image: {img_result['prompt'][:60]}",
                        file_url=img_result["image_url"],
                        file_type="image"
                    )
                    new_db.add(assistant_msg)
                    new_db.commit()
                    new_db.refresh(assistant_msg)
                    msg_id = assistant_msg.id

                    conv_obj = new_db.query(Conversation).filter(Conversation.id == conversation_id).first()
                    if conv_obj:
                        conv_obj.updated_at = datetime.utcnow()
                        if conv_obj.title == "New Chat":
                            conv_obj.title = f"🎨 {img_result['prompt'][:45]}"
                        new_db.commit()
                        t = conv_obj.title
                except Exception as db_err:
                    print(f"[AI Stream] DB error saving image message: {db_err}")
                finally:
                    new_db.close()
                return msg_id, t

            try:
                loop = asyncio.get_running_loop()
            except RuntimeError:
                loop = asyncio.get_event_loop()
            assistant_msg_id, current_title = await loop.run_in_executor(None, _save_image_msg)

            done_data = json.dumps({
                "type": "done",
                "conversation_id": conversation_id,
                "message_id": assistant_msg_id,
                "title": current_title,
                "sources": [],
                "image_url": img_result["image_url"]
            })
            yield f"data: {done_data}\n\n"
            return

        # Web search & grounding check
        user_tz = req.client_timezone or "Asia/Kolkata"
        need_search = should_search_web(query_text, web_search_flag, client_timezone=user_tz)
        sources_found = []

        if need_search:
            status_data = json.dumps({
                "type": "status",
                "message": "🔍 Searching authoritative sources for up-to-date information..."
            })
            yield f"data: {status_data}\n\n"

            # Run web search in threadpool with error safety
            try:
                loop = asyncio.get_running_loop()
            except RuntimeError:
                loop = asyncio.get_event_loop()
            try:
                sources_found = await loop.run_in_executor(
                    None,
                    perform_web_search,
                    query_text,
                    5,
                    user_tz
                )
            except Exception as search_err:
                print(f"[AI Stream] Web search exception for query '{query_text}': {search_err}")
                sources_found = []

            if sources_found:
                src_data = json.dumps({
                    "type": "sources",
                    "sources": sources_found
                })
                yield f"data: {src_data}\n\n"

                grounded_status = json.dumps({
                    "type": "status",
                    "message": f"⚡ Grounded with {len(sources_found)} verified source{'s' if len(sources_found) != 1 else ''}."
                })
                yield f"data: {grounded_status}\n\n"

        # Thinking status
        thinking_data = json.dumps({
            "type": "status",
            "message": "LOKR AI is thinking..."
        })
        yield f"data: {thinking_data}\n\n"

        # Build prompt with verified grounding, temporal anchor & authenticated user identity
        system_prompt = ai_service.build_system_prompt(
            custom_system_prompt=custom_system_prompt,
            sources=sources_found,
            document_text=file_extracted,
            file_name=file_name,
            user_query=query_text,
            client_timezone=user_tz,
            search_attempted=need_search,
            user_name=current_user.name,
            user_preferred_name=preferred_name,
            is_returning_user=is_returning_user,
            saved_memory=custom_system_prompt
        )

        full_response_text = ""
        try:
            async for token in ai_service.generate_chat_stream(
                conversation_history=conv_history,
                system_prompt=system_prompt,
                model=preferred_model
            ):
                full_response_text += token
                chunk_data = json.dumps({
                    "type": "token",
                    "content": token
                })
                yield f"data: {chunk_data}\n\n"

        except Exception as e:
            err_msg = f"⚠️ AI Service Error: {str(e)}"
            print(f"[AI Stream] Exception during generate_chat_stream: {e}")
            full_response_text = err_msg
            yield f"data: {json.dumps({'type': 'token', 'content': err_msg})}\n\n"

        # Ensure response is never blank or empty
        if not full_response_text.strip():
            empty_err = "⚠️ AI Service Error: Model completed without returning text."
            full_response_text = empty_err
            yield f"data: {json.dumps({'type': 'token', 'content': empty_err})}\n\n"

        # Save assistant message to database via threadpool
        try:
            loop = asyncio.get_running_loop()
        except RuntimeError:
            loop = asyncio.get_event_loop()
        assistant_msg_id, current_title = await loop.run_in_executor(
            None, _persist_assistant_message, conversation_id, full_response_text, sources_found, query_text
        )

        # Send final completion event
        done_data = json.dumps({
            "type": "done",
            "conversation_id": conversation_id,
            "message_id": assistant_msg_id,
            "title": current_title,
            "sources": sources_found
        })
        yield f"data: {done_data}\n\n"

    return StreamingResponse(
        sse_event_stream(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"
        }
    )

class DirectImageRequest(BaseModel):
    prompt: str
    width: Optional[int] = 768
    height: Optional[int] = 768

@router.post("/image/generate")
async def generate_image_direct(
    req: DirectImageRequest,
    current_user: User = Depends(get_current_user)
):
    if not req.prompt.strip():
        raise HTTPException(status_code=400, detail="Prompt cannot be empty.")
    clean = clean_image_prompt(req.prompt)
    result = await generate_ai_image(clean, width=req.width or 768, height=req.height or 768)
    return result
